const FLX = window.FLX || {};

/* panoya kopyala */
FLX.copyToClipboard = async function(text) {
  try {
    await navigator.clipboard.writeText(text);
    FLX.toast.show({ message: 'Copied to clipboard', type: 'success', duration: 2000 });
    return true;
  } catch {

    const textarea = document.createElement('textarea');
    textarea.value = text;
    textarea.style.position = 'fixed';
    textarea.style.opacity = '0';
    document.body.appendChild(textarea);
    textarea.select();
    try {
      document.execCommand('copy');
      FLX.toast.show({ message: 'Copied to clipboard', type: 'success', duration: 2000 });
      return true;
    } catch {
      FLX.toast.show({ message: 'Failed to copy', type: 'error', duration: 2000 });
      return false;
    } finally {
      document.body.removeChild(textarea);
    }
  }
};

/* geciktirme */
FLX.debounce = function(fn, delay = 250) {
  let timer;
  return function(...args) {
    clearTimeout(timer);
    timer = setTimeout(() => fn.apply(this, args), delay);
  };
};

/* kisitlama */
FLX.throttle = function(fn, limit = 100) {
  let inThrottle;
  return function(...args) {
    if (!inThrottle) {
      fn.apply(this, args);
      inThrottle = true;
      setTimeout(() => { inThrottle = false; }, limit);
    }
  };
};

/* kimlik olustur */
FLX.generateId = function(prefix = 'flx') {
  return `${prefix}-${Math.random().toString(36).substring(2, 9)}`;
};

/* html kacis */
FLX.escapeHtml = function(str) {
  const div = document.createElement('div');
  div.textContent = str;
  return div.innerHTML;
};

/* dogrusal interpolasyon */
FLX.lerp = function(start, end, factor) {
  return start + (end - start) * factor;
};

/* sinirla */
FLX.clamp = function(value, min, max) {
  return Math.min(Math.max(value, min), max);
};

/* aralik esle */
FLX.mapRange = function(value, inMin, inMax, outMin, outMax) {
  return ((value - inMin) * (outMax - outMin)) / (inMax - inMin) + outMin;
};

/* rastgele tamsayi */
FLX.randomInt = function(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
};

/* rastgele ondalik */
FLX.randomFloat = function(min, max) {
  return Math.random() * (max - min) + min;
};

/* hsl den hex e */
FLX.hslToHex = function(h, s, l) {
  s /= 100;
  l /= 100;
  const a = s * Math.min(l, 1 - l);
  const f = n => {
    const k = (n + h / 30) % 12;
    const color = l - a * Math.max(Math.min(k - 3, 9 - k, 1), -1);
    return Math.round(255 * color).toString(16).padStart(2, '0');
  };
  return `#${f(0)}${f(8)}${f(4)}`;
};

/* hex den rgb ye */
FLX.hexToRgb = function(hex) {
  const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
  return result ? {
    r: parseInt(result[1], 16),
    g: parseInt(result[2], 16),
    b: parseInt(result[3], 16)
  } : null;
};

/* hex den hsl ye */
FLX.hexToHsl = function(hex) {
  const rgb = FLX.hexToRgb(hex);
  if (!rgb) return null;
  let { r, g, b } = rgb;
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h, s, l = (max + min) / 2;
  if (max === min) {
    h = s = 0;
  } else {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r: h = ((g - b) / d + (g < b ? 6 : 0)) / 6; break;
      case g: h = ((b - r) / d + 2) / 6; break;
      case b: h = ((r - g) / d + 4) / 6; break;
    }
  }
  return {
    h: Math.round(h * 360),
    s: Math.round(s * 100),
    l: Math.round(l * 100)
  };
};

/* kaydirma gorunur yap intersectionobserver */
FLX.initScrollReveal = function() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('revealed');

        if (!entry.target.classList.contains('stagger-children')) {
          observer.unobserve(entry.target);
        }
      }
    });
  }, {
    threshold: 0.1,
    rootMargin: '0px 0px -40px 0px'
  });

  document.querySelectorAll('.reveal, .reveal-scale, .stagger-children').forEach(el => {
    observer.observe(el);
  });

  return observer;
};

